    private void anadirMouseReleased(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_anadirMouseReleased
        // TODO add your handling code here:
        if (!titulo.getText().isEmpty() && duracion.getSelectedItem() != null && edadmin.getSelectedItem() != null && genero3.getSelectedItem() != null) {
            pelicula.anadir(titulo.getText(), duracion.getSelectedItem(), edadmin.getSelectedItem(), genero3.getSelectedItem());
            tabla.setModel(pelicula.mostrar());
            titulo.setText("");
            duracion.setSelectedIndex(0);
            edadmin.setSelectedIndex(0);
            genero3.setSelectedIndex(0);
        } else {
            System.out.println("No se han introducido todos los valores");
        }
    }//GEN-LAST:event_anadirMouseReleased

