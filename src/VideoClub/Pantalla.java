    private void eliminarMouseReleased(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_eliminarMouseReleased
        // TODO add your handling code here:
        if (tabla.getSelectedRow() != -1) {
            String nombre = titulo.getText();
            Object duracion2 = duracion.getSelectedIndex();
            Object edad = edadmin.getSelectedIndex();
            Object genero4 = genero3.getSelectedItem();
            pelicula.eliminar(nombre, duracion2, edad, genero4);
            tabla.setModel(pelicula.mostrar());
            eliminar.setEnabled(false);
            modificar.setEnabled(false);
            titulo.setText("");
            duracion.setSelectedIndex(0);
            edadmin.setSelectedIndex(0);
            genero3.setSelectedIndex(0);
        }
    }//GEN-LAST:event_eliminarMouseReleased

