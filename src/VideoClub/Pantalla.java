    private void tablaMouseReleased(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaMouseReleased
        // TODO add your handling code here:
        if (tabla.getSelectedRow() != -1) {
            eliminar.setEnabled(true);
            modificar.setEnabled(true);
            String nombreEdicion = (String) tabla.getValueAt(tabla.getSelectedRow(), 0);
            int duracionEdicion = (Integer) tabla.getValueAt(tabla.getSelectedRow(), 1);
            int edadminimaEdicion = (Integer) tabla.getValueAt(tabla.getSelectedRow(), 2);
            String generoEdicion = (String) tabla.getValueAt(tabla.getSelectedRow(), 3);
            titulo.setText(nombreEdicion);
            duracion.setSelectedIndex(duracionEdicion);
            edadmin.setSelectedIndex(edadminimaEdicion);
            genero3.setSelectedItem(generoEdicion);
        }
    }//GEN-LAST:event_tablaMouseReleased

    private void modificarMouseReleased(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_modificarMouseReleased
        // TODO add your handling code here:
        String nombreEdicion = (String) tabla.getValueAt(tabla.getSelectedRow(), 0);
        String nombre = titulo.getText();
        Object duracion2 = duracion.getSelectedIndex();
        Object edad2 = edadmin.getSelectedIndex();
        Object genero2 = genero3.getSelectedItem();
        pelicula.modificar(nombre, duracion2, edad2, genero2, nombreEdicion);
        tabla.setModel(pelicula.mostrar());
        eliminar.setEnabled(false);
        modificar.setEnabled(false);
        titulo.setText("");
        duracion.setSelectedIndex(0);
        edadmin.setSelectedIndex(0);
        genero3.setSelectedIndex(0);
    }//GEN-LAST:event_modificarMouseReleased

